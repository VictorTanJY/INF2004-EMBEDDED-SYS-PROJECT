#!/usr/bin/env python3
"""Extract Code 39 element widths from the instructor's BARCODE.pptx.

Usage:  python3 make_vectors.py BARCODE.pptx > vectors_slides.h
Needs LibreOffice (soffice), pdftoppm and Pillow.  The slide is 338.67 mm
wide on screen; widths are written in micrometres at that size (the
tests also scale them to an A4 print, x 297 / 338.67).
"""
import os, subprocess, sys, tempfile
from PIL import Image

SLIDES = {2: 'A', 3: 'A', 4: 'A', 6: 'F', 7: 'F', 8: 'F',
          10: 'Z', 11: 'Z', 12: 'Z', 13: 'W', 14: 'X', 15: 'Y'}

def runs(im, y):
    w = im.size[0]
    px = [1 if im.getpixel((x, y)) < 128 else 0 for x in range(w)]
    out, cur, n = [], px[0], 0
    for p in px:
        if p == cur:
            n += 1
        else:
            out.append((cur, n)); cur, n = p, 1
    out.append((cur, n))
    while out and out[0][0] == 0: out.pop(0)
    while out and out[-1][0] == 0: out.pop()
    return out

def main(pptx):
    tmp = tempfile.mkdtemp()
    subprocess.run(['soffice', '--headless', '--convert-to', 'pdf', '--outdir', tmp, pptx],
                   check=True, capture_output=True)
    pdf = os.path.join(tmp, os.path.splitext(os.path.basename(pptx))[0] + '.pdf')
    subprocess.run(['pdftoppm', '-r', '300', '-png', pdf, os.path.join(tmp, 's')], check=True)
    print('/* Generated by make_vectors.py from BARCODE.pptx -- do not edit. */')
    print('/* Element widths in um at on-screen slide size (slide = 338.67 mm). */')
    names = []
    for slide, ch in SLIDES.items():
        im = Image.open(os.path.join(tmp, 's-%02d.png' % slide)).convert('L')
        um_per_px = 338670.0 / im.size[0]
        y = im.size[1] // 2 if slide < 13 else int(im.size[1] * 0.45)
        r = runs(im, y)
        assert len(r) == 29, (slide, len(r))
        widths = [int(round(n * um_per_px)) for _, n in r]
        name = 'k_slide%02d_%c' % (slide, ch)
        names.append((name, ch, slide))
        print('static uint32_t const %s[29] = { %s };' % (name, ', '.join(map(str, widths))))
    print('typedef struct { uint32_t const * p_w; char ch; int slide; } slide_vec_t;')
    print('static slide_vec_t const k_slides[] = {')
    for (name, ch, slide) in names:
        print('    { %s, \'%c\', %d },' % (name, ch, slide))
    print('};')

if __name__ == '__main__':
    main(sys.argv[1])
