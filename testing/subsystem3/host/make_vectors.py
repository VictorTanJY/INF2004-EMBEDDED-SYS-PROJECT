#!/usr/bin/env python3
"""Extract Code 39 element widths from the instructor's BARCODE.pptx.

Usage:  python3 make_vectors.py BARCODE.pptx
Writes vectors_slides.h and vectors_slides.c next to this script; run
tools/barr_format.sh afterwards to lay them out.
Needs LibreOffice (soffice), pdftoppm and Pillow.  The slide is 338.67 mm
wide on screen; widths are written in micrometres at that size (the
tests also scale them to an A4 print, x 297 / 338.67).
"""
import os, subprocess, sys, tempfile
from PIL import Image

SLIDES = {2: 'A', 3: 'A', 4: 'A', 6: 'F', 7: 'F', 8: 'F',
          10: 'Z', 11: 'Z', 12: 'Z', 13: 'W', 14: 'X', 15: 'Y'}

def runs(im, y):
    w = im.size[0]
    px = [1 if im.getpixel((x, y)) < 128 else 0 for x in range(w)]
    out, cur, n = [], px[0], 0
    for p in px:
        if p == cur:
            n += 1
        else:
            out.append((cur, n)); cur, n = p, 1
    out.append((cur, n))
    while out and out[0][0] == 0: out.pop(0)
    while out and out[-1][0] == 0: out.pop()
    return out

def main(pptx):
    tmp = tempfile.mkdtemp()
    subprocess.run(['soffice', '--headless', '--convert-to', 'pdf', '--outdir', tmp, pptx],
                   check=True, capture_output=True)
    pdf = os.path.join(tmp, os.path.splitext(os.path.basename(pptx))[0] + '.pdf')
    subprocess.run(['pdftoppm', '-r', '300', '-png', pdf, os.path.join(tmp, 's')], check=True)
    arrays = []
    names = []
    for slide, ch in SLIDES.items():
        im = Image.open(os.path.join(tmp, 's-%02d.png' % slide)).convert('L')
        um_per_px = 338670.0 / im.size[0]
        y = im.size[1] // 2 if slide < 13 else int(im.size[1] * 0.45)
        r = runs(im, y)
        assert len(r) == 29, (slide, len(r))
        widths = [int(round(n * um_per_px)) for _, n in r]
        name = 'g_slide%02d_%c' % (slide, ch.lower())
        names.append((name, ch, slide))
        arrays.append('static uint32_t const %s[SLIDE_VEC_ELEMS] = {%s};'
                      % (name, ', '.join(map(str, widths))))
    banner = '/* Generated by make_vectors.py from BARCODE.pptx -- do not edit. */'
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, 'vectors_slides.h'), 'w') as out:
        out.write('\n'.join([
            banner,
            '#ifndef VECTORS_SLIDES_H',
            '#define VECTORS_SLIDES_H',
            '',
            '#include <stdint.h>',
            '',
            '#define SLIDE_VEC_ELEMS 29u /* one *X* barcode: 3 characters + 2 gaps */',
            '#define SLIDE_VEC_COUNT %du' % len(names),
            '',
            'typedef struct',
            '{',
            '    uint32_t const * p_w;',
            '    char             chr;',
            '    int32_t          slide;',
            '} vectors_slides_vec_t;',
            '',
            'extern vectors_slides_vec_t const g_slides[SLIDE_VEC_COUNT];',
            '',
            '#endif /* VECTORS_SLIDES_H */',
            '',
            '/*** end of file ***/',
            '']))
    with open(os.path.join(here, 'vectors_slides.c'), 'w') as out:
        out.write('\n'.join(
            [banner, '#include "vectors_slides.h"', '',
             '/* Element widths in um at on-screen slide size (slide = 338.67 mm). */']
            + arrays
            + ['', 'vectors_slides_vec_t const g_slides[SLIDE_VEC_COUNT] = {']
            + ['    {%s, \'%c\', %d},' % item for item in names]
            + ['};', '', '/*** end of file ***/', '']))

if __name__ == '__main__':
    main(sys.argv[1])
